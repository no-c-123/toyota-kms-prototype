def load_documents():
    return json.loads((DATA / "documents.json").read_text(encoding="utf-8"))


def load_concepts():
    return json.loads((DATA / "concepts.json").read_text(encoding="utf-8"))


def doc_text(d, lang=None):
    """Text indexed for a document. Titles count twice. lang=None -> both languages."""
    langs = [lang] if lang else ["en", "es"]
    return " ".join(f"{d['title_' + l]} {d['title_' + l]} {d['text_' + l]}" for l in langs)


def make_vectorizer():
    # sklearn formulas (replicated in JS): tf = 1 + ln(count); idf = ln((1+n)/(1+df)) + 1; L2 norm
    return TfidfVectorizer(analyzer=tp.analyzer, sublinear_tf=True, norm="l2", smooth_idf=True)


def export_vectorizer(vec):
    vocab = {t: int(i) for t, i in vec.vocabulary_.items()}
    return {"vocab": vocab, "idf": [round(float(x), 6) for x in vec.idf_]}


def sparse_rows(matrix, digits=5):
    """CSR matrix -> list of [[index, weight], ...] per row (compact JSON)."""
    rows = []
    for r in range(matrix.shape[0]):
        row = matrix.getrow(r)
        rows.append([[int(i), round(float(v), digits)] for i, v in zip(row.indices, row.data)])
    return rows


def write_js_module(path, obj):
    """Write data as an ES module so Vercel bundles it with the serverless functions."""
    path.write_text("// Generated by ml/build_artifacts.py. Do not edit by hand.\nexport default " +
                    json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")


def write_json(path, obj, indent=None):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=indent), encoding="utf-8")
